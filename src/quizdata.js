// wrong answers that look just as plausible: same category & gender, then same country / same kind
function lookAlikes(x) {
  const same = CELEB.filter((y) => y !== x && y.c === x.c && y.g === x.g);
  const score = (y) => (x.n && y.n === x.n ? 2 : 0) + (x.t && y.t === x.t ? 3 : 0) + Math.random();
  const pick = same.sort((p, q) => score(q) - score(p)).slice(0, 3).map((y) => y.a);
  if (pick.length < 3) pick.push(...shuf(CELEB.filter((y) => y !== x && y.c === x.c && !pick.includes(y.a))).slice(0, 3 - pick.length).map((y) => y.a));
  return pick;
}

function catBank(c) {
  if (c === 'guess') return CELEB.map((x) => {
    const o = lookAlikes(x);
    // if the first clue's country already rules out the wrong answers, open with the second clue instead
    const sameNat = x.n && o.every((n) => (CELEB.find((y) => y.a === n) || {}).n === x.n);
    const h = x.c !== 'nabi' && !sameNat ? [x.h[1], x.h[0], x.h[2]] : x.h;
    return { cat: CELEB_CATS[x.c], h, a: x.a, o };
  });
  if (c === 'trivia') return TRIVIA.map(([q, a, ...o]) => ({ cat: 'ثقافة عامة', q, a, o }));
  if (c === 'tf') return TF.map(([q, v, x]) => ({ cat: 'صح ولا غلط؟', q, x, a: v ? 'صح ✅' : 'غلط ❌', o: [v ? 'غلط ❌' : 'صح ✅'], two: true, fixed: ['صح ✅', 'غلط ❌'] }));
  if (c === 'flags') return COUNTRIES.map(([n, f]) => ({ cat: 'علم أي دولة؟', q: f, big: true, a: n, pool: COUNTRIES.map((x) => x[0]) }));
  if (c === 'capitals') { const cs = COUNTRIES.filter((x) => x[2]); return cs.map(([n, f, cap]) => ({ cat: 'العواصم', q: `${f} ماذا عاصمة ${n}؟`, a: cap, pool: cs.map((x) => x[2]) })); }
  if (c === 'proverbs') return PROVERBS.map(([q, a]) => ({ cat: 'كمّل المثل', q, a, pool: PROVERBS.map((x) => x[1]) }));
  if (c === 'dishes') return DISHES.map(([a, h]) => ({ cat: 'أكلات عربية', h, a, pool: DISHES.map((x) => x[0]) }));
  if (c === 'scramble') {
    const ws = [];
    for (const L in W) W[L].forEach((line, k) => line.split(' ').forEach((w) => { if (w.length >= 3 && w.length <= 7 && !/[ّ]/.test(w)) ws.push([w, ['اسم', 'جماد', 'حيوان', 'نبات', 'بلاد'][k]]); }));
    return shuf(ws).slice(0, 40).map(([w, k]) => {
      let s = w; for (let t = 0; t < 8 && s === w; t++) s = shuf([...w]).join('');
      return { cat: `رتّب الحروف — ${k}`, q: [...s].join(' '), big: true, a: w, pool: ws.filter((x) => x[1] === k && x[0] !== w).map((x) => x[0]) };
    });
  }
  if (c === 'wyr') return WYR.map(([a, b]) => ({ cat: 'لو خيّروك…', q: 'ماذا تختار؟', a, o: [b], wyr: true, keep: true }));
  return [];
}

function mathQ() {
  const t = Math.floor(Math.random() * 4);
  let a, b, ans, q;
  if (t === 0) { a = 10 + Math.floor(Math.random() * 90); b = 10 + Math.floor(Math.random() * 90); ans = a + b; q = `${a} + ${b}`; }
  else if (t === 1) { a = 30 + Math.floor(Math.random() * 90); b = 5 + Math.floor(Math.random() * a); ans = a - b; q = `${a} − ${b}`; }
  else if (t === 2) { a = 3 + Math.floor(Math.random() * 10); b = 3 + Math.floor(Math.random() * 10); ans = a * b; q = `${a} × ${b}`; }
  else { b = 2 + Math.floor(Math.random() * 9); ans = 2 + Math.floor(Math.random() * 11); a = b * ans; q = `${a} ÷ ${b}`; }
  const o = new Set(); while (o.size < 3) { const d = ans + (Math.floor(Math.random() * 7) - 3) * (t === 2 ? b > 1 ? 1 : 2 : 1) + (Math.random() < 0.5 ? 10 : -10) * (Math.random() < 0.3 ? 1 : 0); if (d !== ans && d >= 0) o.add(d); }
  return { cat: 'رياضيات سريعة', q: q + ' = ؟', big: true, a: String(ans), o: [...o].map(String) };
}

export const QUIZ_KINDS = {
  guess: { n: 10, hints: true, ms: 15000 },
  trivia: { n: 10 }, tf: { n: 12, ms: 9000 }, flags: { n: 12, ms: 12000 }, capitals: { n: 10 }, proverbs: { n: 10 }, dishes: { n: 10, hints: true },
  scramble: { n: 10, ms: 20000 }, math: { n: 12, ms: 10000 }, wyr: { n: 10, ms: 15000 },
};

// returns array of {cat, h?|q, a, opts:[...4 or 2], big?, wyr?}
export function makeQuestions(kind, catFilter) {
  const cfg = QUIZ_KINDS[kind];
  let items = kind === 'math' ? Array.from({ length: cfg.n }, mathQ) : shuf(catBank(kind).filter((x) => !catFilter || catFilter === 'mix' || x.cat === catFilter)).slice(0, cfg.n);
  return items.map((x) => {
    const others = x.o ? x.o.slice() : pickOthers([...new Set(x.pool)], x.a, 3);
    const opts = x.fixed ? x.fixed.slice() : x.keep ? [x.a, ...others] : shuf([x.a, ...others]);
    return { cat: x.cat, h: x.h, q: x.q, x: x.x, big: x.big, a: x.a, opts, wyr: !!x.wyr };
  });
}
